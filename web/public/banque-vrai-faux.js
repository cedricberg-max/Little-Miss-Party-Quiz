/**
 * Tire [n] affirmations au hasard ([niveau] : ce niveau seulement), jamais une dont le texte est dans [exclus] : à peu
 * près autant de vraies que de fausses (une de plus d'un côté ou de l'autre si [n] est impair), dans un ordre mélangé.
 * Fonction pure (à [rng] près), testée.
 */
export function tirerAffirmations(n, { niveau = null, exclus = new Set(), rng = Math.random, liste = AFFIRMATIONS } = {}) {
  const melange = (xs) => {
    const out = [...xs];
    for (let i = out.length - 1; i > 0; i--) {
      const j = Math.floor(rng() * (i + 1));
      [out[i], out[j]] = [out[j], out[i]];
    }
    return out;
  };
  const libres = liste.filter((x) => (!niveau || x.niveau === niveau) && !exclus.has(x.text));
  const vraies = melange(libres.filter((x) => x.vrai));
  const fausses = melange(libres.filter((x) => !x.vrai));
  const nVraies = Math.floor(n / 2) + (n % 2 && rng() < 0.5 ? 1 : 0);
  const pris = [...vraies.slice(0, nVraies), ...fausses.slice(0, n - nVraies)];
  // Pas assez d'un côté : on complète avec l'autre.
  const reste = [...vraies.slice(nVraies), ...fausses.slice(n - nVraies)];
  return melange([...pris, ...melange(reste).slice(0, Math.max(0, n - pris.length))]);
}
